/**
 * Doc 05 §11.1 — THE GOLDEN MATRIX.
 *
 * Every cell is generated by the REAL resolver — `allAccessMap` / `computeProjectMap` /
 * `atomsAt`, the same pure functions `PermissionResolver` delegates to (the service adds
 * Prisma and Redis and nothing else) — and snapshotted to a COMMITTED CSV. There is no
 * second implementation of the rules here; a test that re-derives the expected answer
 * agrees with itself, not with the system.
 *
 * The point is NOT that the matrix passes today. The point is that a change to the
 * resolver arrives in review as a readable diff in
 * `apps/api/test/fixtures/permission-matrix.csv`, where a human reads "this cell went
 * from deny to allow" and asks whether that was intended. A diff with no corresponding
 * intentional change fails review, not just CI.
 *
 * Regenerate deliberately, never reflexively:
 *
 *     UPDATE_MATRIX=1 pnpm --filter @schemaloom/api test golden-matrix
 *
 * DEVIATION from §11.1, stated so nobody thinks it drifted: the doc emits all 11
 * predicates per (subject, resource) cell, which repeats `canOpenProject` and
 * `fieldVisibility(fld_sal)` eight times per subject although neither is a function of
 * the resource. One behaviour change would then surface as eight identical diff lines,
 * which is noise in exactly the artefact whose whole value is signal. They are emitted
 * once per subject with resource `-` instead. Same coverage, 2,220 rows instead of 2,640.
 */

