function liveGrants(specs: readonly GrantSpec[]): LiveGrant[] {
  return specs.map((spec, i) => ({
    id: `gr_${String(i)}`,
    resourceType: spec.ref.type,
    resourceId: spec.ref.id,
    principalKey: spec.principal,
    atoms: [...BUILT_IN_ROLES[spec.role]],
    canUseAi: spec.canUseAi ?? false,
    canViewRestricted: spec.canViewRestricted ?? false,
    expiresAt: null,
    linkExpiresAt: null,
  }));
}

/** `PermissionResolver.resolveProject`'s branch, minus the two I/O reads. */
function mapFor(row: MatrixSubject, mode: RestrictedFieldMode): ProjectPermissionMap {
  const { orgRole, subject } = row;
  if (orgRole === 'owner' || orgRole === 'admin') {
    return allAccessMap(PROJECT, SKELETON, subject, orgRole, mode, NOW);
  }
  const principals =
    subject.kind === 'share_link'
      ? [LINK_KEY]
      : [ANA_KEY, ...new Set(row.grants.map((g) => g.principal).filter((p) => p !== ANA_KEY))];

  return computeProjectMap({
    projectId: PROJECT,
    subject,
    orgRole,
    principals,
    grants: liveGrants(row.grants),
    skeleton: SKELETON,
    restrictedFieldMode: mode,
    nowMs: NOW,
  });
}

/**
 * The slice of `VisibilityFilter.contextFrom` that `fieldVisibility` actually reads.
 * Every value in it comes from the resolver; the three keys below are a projection, not
 * a rule.
 */
function visibilityContextFor(map: ProjectPermissionMap): VisibilityContext {
  return {
    projectId: PROJECT,
    subjectKind: 'user',
    subjectKey: map.subjectKey,
    canOpenProject: canOpenProject(map),
    visibleEntityIds: visibleEntityIds(map, SKELETON),
    restrictedOkEntityIds: restrictedOkEntityIds(map, SKELETON),
    areasWithAtoms: new Set<string>(),
    restrictedFieldMode: map.restrictedFieldMode,
    totalEntityCount: SKELETON.entities.length,
    entitiesWithRestrictedFields: SKELETON.entitiesWithRestrictedFields,
  };
}

export function generateMatrix(): string[] {
  const lines: string[] = [CSV_HEADER];

  for (const mode of ['mask', 'hide'] as const) {
    for (const row of SUBJECTS) {
      const map = mapFor(row, mode);

      for (const ref of RESOURCES) {
        const atoms = atomsAt(map, SKELETON, ref);
        for (const atom of PERMISSION_ATOMS) {
          const result = atoms.has(atom) ? 'allow' : 'deny';
          lines.push(`${mode},${row.name},${ref.id},${atom},${result}`);
        }
      }

      lines.push(`${mode},${row.name},-,canOpenProject,${String(canOpenProject(map))}`);
      const visibility = fieldVisibility(visibilityContextFor(map), FIELDS, FLD_SAL);
      lines.push(`${mode},${row.name},-,fieldVisibility(fld_sal),${visibility}`);
    }
  }
  return lines;
}

/** Only the cells that moved, so the failure message IS the review diff. */
function driftingCells(committed: readonly string[], generated: readonly string[]): string[] {
  const out: string[] = [];
  const end = Math.max(committed.length, generated.length);
  for (let i = 0; i < end && out.length < 50; i += 1) {
    if (committed[i] === generated[i]) continue;
    out.push(`row ${String(i + 1)}: was "${committed[i] ?? '<absent>'}" now "${generated[i] ?? '<absent>'}"`);
  }
  return out;
}

describe('the golden permission matrix', () => {
  const generated = generateMatrix();

  it('covers every subject x resource x atom, plus the two derived predicates', () => {
    const perSubject = RESOURCES.length * PERMISSION_ATOMS.length + 2;
    expect(generated).toHaveLength(1 + 2 * SUBJECTS.length * perSubject);
  });

  it('matches the committed CSV snapshot', () => {
    if (process.env.UPDATE_MATRIX === '1') {
      mkdirSync(dirname(CSV_PATH), { recursive: true });
      writeFileSync(CSV_PATH, `${generated.join('\n')}\n`, 'utf8');
    }
    const committed = readFileSync(CSV_PATH, 'utf8').trimEnd().split(/\r?\n/);

    expect(
      driftingCells(committed, generated),
      'The resolver now answers differently than the committed matrix. If that was ' +
        'intentional, regenerate with UPDATE_MATRIX=1 and review the CSV diff cell by cell.',
    ).toEqual([]);
  });
});
